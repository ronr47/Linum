#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

void render_markdown(FILE *in, FILE *out) {
    char line[1024];
    bool in_code_block = false;
    bool in_list = false;

    fprintf(out, "<!DOCTYPE html>\n<html>\n<head>\n");
    fprintf(out, "<meta charset=\"utf-8\">\n");
    fprintf(out, "<title>Generated by mgen</title>\n");
    fprintf(out, "<style>\n");
    fprintf(out, "body { font-family: sans-serif; max-width: 800px; margin: 40px auto; padding: 0 20px; line-height: 1.6; color: #333; background: #f9f9f9; }\n");
    fprintf(out, "pre { background: #f4f4f4; border: 1px solid #ddd; border-left: 3px solid #666; color: #666; page-break-inside: avoid; font-family: monospace; font-size: 14px; line-height: 1.6; margin-bottom: 1.6em; max-width: 100%%; overflow: auto; padding: 1em 1.5em; display: block; word-wrap: break-word; }\n");
    fprintf(out, "code { font-family: monospace; background: #eee; padding: 2px 4px; border-radius: 3px; }\n");
    fprintf(out, "pre code { background: none; padding: 0; }\n");
    fprintf(out, "</style>\n</head>\n<body>\n");

    while (fgets(line, sizeof(line), in)) {
        line[strcspn(line, "\r\n")] = 0;

        if (strncmp(line, "```", 3) == 0) {
            if (in_list) {
                fprintf(out, "</ul>\n");
                in_list = false;
            }
            if (in_code_block) {
                fprintf(out, "</code></pre>\n");
                in_code_block = false;
            } else {
                fprintf(out, "<pre><code>");
                in_code_block = true;
            }
            continue;
        }

        if (in_code_block) {
            fprintf(out, "%s\n", line);
            continue;
        }

        if (strncmp(line, "# ", 2) == 0) {
            if (in_list) { fprintf(out, "</ul>\n"); in_list = false; }
            fprintf(out, "<h1>%s</h1>\n", line + 2);
        } else if (strncmp(line, "### ", 4) == 0) {
            if (in_list) { fprintf(out, "</ul>\n"); in_list = false; }
            fprintf(out, "<h3>%s</h3>\n", line + 4);
        } else if (strncmp(line, "## ", 3) == 0) {
            if (in_list) { fprintf(out, "</ul>\n"); in_list = false; }
            fprintf(out, "<h2>%s</h2>\n", line + 3);
        } else if (strncmp(line, "- ", 2) == 0) {
            if (!in_list) {
                fprintf(out, "<ul>\n");
                in_list = true;
            }
            fprintf(out, "  <li>%s</li>\n", line + 2);
        } else {
            if (in_list) {
                fprintf(out, "</ul>\n");
                in_list = false;
            }
            if (strlen(line) > 0) {
                fprintf(out, "<p>%s</p>\n", line);
            } else {
                fprintf(out, "<br>\n");
            }
        }
    }

    if (in_list) {
        fprintf(out, "</ul>\n");
    }
    if (in_code_block) {
        fprintf(out, "</code></pre>\n");
    }

    fprintf(out, "</body>\n</html>\n");
}

int main(int argc, char *argv[]) {
    if (argc != 3) {
        fprintf(stderr, "Usage: %s <input.md> <output.html>\n", argv[0]);
        return 1;
    }

    FILE *in = fopen(argv[1], "r");
    if (!in) {
        perror("Failed to open input file");
        return 1;
    }

    FILE *out = fopen(argv[2], "w");
    if (!out) {
        perror("Failed to open output file");
        fclose(in);
        return 1;
    }

    render_markdown(in, out);

    fclose(in);
    fclose(out);

    return 0;
}
