#!/usr/bin/env python3
import sys
import re

class AetherCompiler:
    def __init__(self, source: str):
        self.lines = [l.strip() for l in source.splitlines() if l.strip() and not l.strip().startswith("//")]
        self.reg_map = {"r0": "x0", "r1": "x1", "r2": "x2", "r3": "x3", "r4": "x4"}
        self.asm = []

    def compile(self) -> str:
        self.asm.append("// Structural Output generated by Aether-0. Zero Stack / Zero Libc.")
        self.asm.append(".global _start")
        self.asm.append(".section .rodata")
        self.asm.append(".align 4")
        self.asm.append(".L_telemetry_ok:")
        self.asm.append("    .ascii \"STATUS=EQUILIBRIUM\\n\"")
        self.asm.append("    .equ TELEMETRY_OK_LEN, . - .L_telemetry_ok")
        self.asm.append(".L_telemetry_fault:")
        self.asm.append("    .ascii \"STATUS=ANOMALY_DETECTED\\n\"")
        self.asm.append("    .equ TELEMETRY_FAULT_LEN, . - .L_telemetry_fault")
        self.asm.append(".section .text")
        self.asm.append(".align 4")
        self.asm.append("_start:")

        for line in self.lines:
            if line.startswith((".target", ".entry", "register")):
                continue
            m = re.match(r"pipeline\s+([a-zA-Z0-9_]+)\s*\{", line)
            if m:
                if m.group(1) != "commander_entry":
                    self.asm.append(f"{m.group(1)}:")
                continue
            if line == "}":
                continue
            self._translate(line.rstrip(";"))
        return "\n".join(self.asm)

    def _translate(self, stmt: str):
        m = re.match(r"(r\d)\s*<-\s*(.+)", stmt)
        if m:
            dest = self.reg_map[m.group(1)]
            expr = m.group(2).strip()
            arith = re.match(r"(r\d)\s*([\+\-\*])\s*(r\d)", expr)
            if arith:
                op1, sym, op2 = self.reg_map[arith.group(1)], arith.group(2), self.reg_map[arith.group(3)]
                if sym == "*": self.asm.append(f"    mul     {dest}, {op1}, {op2}")
                elif sym == "+": self.asm.append(f"    adds    {dest}, {op1}, {op2}")
                elif sym == "-": self.asm.append(f"    subs    {dest}, {op1}, {op2}")
                return
            if expr.lstrip("-").isdigit():
                self.asm.append(f"    mov     {dest}, #{int(expr)}")
                return
        m = re.match(r"on\s+(r\d)\s*<=\s*0\s+divert\s+([a-zA-Z0-9_]+)", stmt)
        if m:
            self.asm.append(f"    ble     {m.group(2)}")
            return
        m = re.match(r"trap\s+vector\s+(0x[0-9a-fA-F]+)", stmt)
        if m:
            vec = int(m.group(1), 16)
            if vec == 0x40:
                self.asm.append("    mov     x0, #1")
                self.asm.append("    adr     x1, .L_telemetry_ok")
                self.asm.append("    mov     x2, #TELEMETRY_OK_LEN")
                self.asm.append("    mov     x8, #64")
                self.asm.append("    svc     #0")
            elif vec == 0x5D:
                self.asm.append("    mov     x0, #0")
                self.asm.append("    mov     x8, #93")
                self.asm.append("    svc     #0")
            return

with open(sys.argv[1], "r") as f: src = f.read()
with open(sys.argv[2], "w") as f: f.write(AetherCompiler(src).compile() + "\n")
