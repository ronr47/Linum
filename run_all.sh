#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# VISUAL TELEMETRY & TTY MATRIX ENGINE
# ==============================================================================
C_RESET="\033[0m"
C_CYAN="\033[38;5;51m"
C_BLUE="\033[38;5;39m"
C_GREEN="\033[38;5;82m"
C_PURPLE="\033[38;5;141m"
C_AMBER="\033[38;5;214m"
C_GRAY="\033[38;5;240m"
C_WHITE="\033[1;37m"

sleep_tick() {
    sleep 0.03 2>/dev/null || sleep 1
}

step_header() {
    local phase="$1"
    local title="$2"
    echo -e "\n${C_GRAY}┌───[ ${C_CYAN}${phase}${C_GRAY} ]───────────────────────────────────────────────────${C_RESET}"
    echo -e "${C_GRAY}│ ${C_WHITE}● ${title}${C_RESET}"
    echo -e "${C_GRAY}└───${C_RESET}"
}

telemetry_log() {
    local label="$1"
    local msg="$2"
    printf "  ${C_GRAY}[${C_BLUE}%-10s${C_GRAY}]${C_RESET} %s\n" "$label" "$msg"
    sleep_tick
}

matrix_trace() {
    local text="$1"
    echo -ne "  ${C_PURPLE}► ${C_GRAY}"
    for (( i=0; i<${#text}; i++ )); do
        echo -ne "${text:$i:1}"
        sleep 0.004 2>/dev/null || true
    done
    echo -e "${C_RESET}"
}

clear 2>/dev/null || true
cat << "BANNER"
[38;5;39m    ___   ______ _____ _   _ _____ ____        ____ 
[38;5;45m   /   | / ____/_  __/ / / / ____/ __ \      / __ \
[38;5;51m  / /| |/ __/   / / / /_/ / __/ / /_/ /_____/ / / /
[38;5;87m / ___ / /___  / / / __  / /___/ _, _/_____/ /_/ / 
[38;5;123m/_/  |_|_____/ /_/ /_/ /_/_____/_/ |_|      \____/  
[38;5;141m:: HARDWARE COMMANDER & COMPILER MATRIX PIPELINE ::[0m
BANNER

# ==============================================================================
# PHASE 1: PREFLIGHT HOST IDENTIFICATION
# ==============================================================================
step_header "STAGE 01" "ENVIRONMENT DISCOVERY & HARDWARE TARGETING"

ARCH=$(uname -m)
telemetry_log "HOST_ARCH" "Physical reporting architecture: ${C_CYAN}${ARCH}${C_RESET}"

if [[ "${ARCH}" != "aarch64" && "${ARCH}" != "arm64" ]]; then
    echo -e "  ${C_AMBER}Error: Native AArch64 substrate required.${C_RESET}" >&2
    exit 1
fi

PAGE_SIZE=$(getconf PAGESIZE 2>/dev/null || echo "4096")
telemetry_log "PAGE_SIZE" "Target MMU Page Boundary: ${C_CYAN}${PAGE_SIZE} bytes${C_RESET}"

if ! command -v python3 >/dev/null 2>&1; then
    echo -e "  ${C_AMBER}Error: Python 3 runtime missing.${C_RESET}" >&2
    exit 1
fi
telemetry_log "COMPILER" "Bootstrap driver resolved: $(command -v python3)"

# ==============================================================================
# PHASE 2: SYNTHESIZING DSL & TARGET SOURCE
# ==============================================================================
step_header "STAGE 02" "SYNTHESIZING DSL AND COMPILER NUCLEUS"

telemetry_log "EMIT" "Writing Aether-0 Hardware Program [commander.a0]..."
cat << 'EOF_A0' > commander.a0
.target aarch64
.entry commander_entry

register r0: i64;       // Sensory Input State
register r1: i64;       // Weight Matrix Parameter
register r2: i64;       // Baseline Bias
register r3: i64;       // Accumulator State

pipeline commander_entry {
    r0 <- 5;
    r1 <- 3;
    r2 <- -4;
    
    // Homomorphic MAC projection: Y = (X * W) + B
    r3 <- r0 * r1;
    r3 <- r3 + r2;
    
    // Signum Homeostatic Boundary Decision
    on r3 <= 0 divert trigger_stabilizer;
    
    // Emission of Equilibrium Invariant
    trap vector 0x40;
    trap vector 0x5D;
}

pipeline trigger_stabilizer {
    trap vector 0x40;
    trap vector 0x5D;
}
EOF_A0
matrix_trace "AST Root: pipeline commander_entry mapped to static register plane."

telemetry_log "EMIT" "Writing Aether-0 Direct Compiler Nucleus [aether0c.py]..."
cat << 'EOF_COMPILER' > aether0c.py
#!/usr/bin/env python3
import sys
import re

class AetherCompiler:
    def __init__(self, source: str):
        self.lines = [l.strip() for l in source.splitlines() if l.strip() and not l.strip().startswith("//")]
        self.reg_map = {"r0": "x0", "r1": "x1", "r2": "x2", "r3": "x3", "r4": "x4"}
        self.asm = []

    def compile(self) -> str:
        self.asm.append("// Structural Output generated by Aether-0. Zero Stack / Zero Libc.")
        self.asm.append(".global _start")
        self.asm.append(".section .rodata")
        self.asm.append(".align 4")
        self.asm.append(".L_telemetry_ok:")
        self.asm.append("    .ascii \"STATUS=EQUILIBRIUM\\n\"")
        self.asm.append("    .equ TELEMETRY_OK_LEN, . - .L_telemetry_ok")
        self.asm.append(".L_telemetry_fault:")
        self.asm.append("    .ascii \"STATUS=ANOMALY_DETECTED\\n\"")
        self.asm.append("    .equ TELEMETRY_FAULT_LEN, . - .L_telemetry_fault")
        self.asm.append(".section .text")
        self.asm.append(".align 4")
        self.asm.append("_start:")

        for line in self.lines:
            if line.startswith((".target", ".entry", "register")):
                continue
            m = re.match(r"pipeline\s+([a-zA-Z0-9_]+)\s*\{", line)
            if m:
                if m.group(1) != "commander_entry":
                    self.asm.append(f"{m.group(1)}:")
                continue
            if line == "}":
                continue
            self._translate(line.rstrip(";"))
        return "\n".join(self.asm)

    def _translate(self, stmt: str):
        m = re.match(r"(r\d)\s*<-\s*(.+)", stmt)
        if m:
            dest = self.reg_map[m.group(1)]
            expr = m.group(2).strip()
            arith = re.match(r"(r\d)\s*([\+\-\*])\s*(r\d)", expr)
            if arith:
                op1, sym, op2 = self.reg_map[arith.group(1)], arith.group(2), self.reg_map[arith.group(3)]
                if sym == "*": self.asm.append(f"    mul     {dest}, {op1}, {op2}")
                elif sym == "+": self.asm.append(f"    adds    {dest}, {op1}, {op2}")
                elif sym == "-": self.asm.append(f"    subs    {dest}, {op1}, {op2}")
                return
            if expr.lstrip("-").isdigit():
                self.asm.append(f"    mov     {dest}, #{int(expr)}")
                return
        m = re.match(r"on\s+(r\d)\s*<=\s*0\s+divert\s+([a-zA-Z0-9_]+)", stmt)
        if m:
            self.asm.append(f"    ble     {m.group(2)}")
            return
        m = re.match(r"trap\s+vector\s+(0x[0-9a-fA-F]+)", stmt)
        if m:
            vec = int(m.group(1), 16)
            if vec == 0x40:
                self.asm.append("    mov     x0, #1")
                self.asm.append("    adr     x1, .L_telemetry_ok")
                self.asm.append("    mov     x2, #TELEMETRY_OK_LEN")
                self.asm.append("    mov     x8, #64")
                self.asm.append("    svc     #0")
            elif vec == 0x5D:
                self.asm.append("    mov     x0, #0")
                self.asm.append("    mov     x8, #93")
                self.asm.append("    svc     #0")
            return

with open(sys.argv[1], "r") as f: src = f.read()
with open(sys.argv[2], "w") as f: f.write(AetherCompiler(src).compile() + "\n")
EOF_COMPILER
matrix_trace "Parser initialized: Affine register types bound to AAPCS64."

# ==============================================================================
# PHASE 3: COMPILATION & TOOLCHAIN ADAPTATION
# ==============================================================================
step_header "STAGE 03" "AETHER-0 TRANSLATION & LINKAGE"

telemetry_log "PASS 1" "Compiling high-level hardware grammar to machine IR..."
python3 aether0c.py commander.a0 commander.s
matrix_trace "Generated AArch64 Assembly [commander.s] verified clean."

telemetry_log "PASS 2" "Building static standalone executable..."
# Use clang or gcc driver to link static freestanding binary with kernel-safe layout
if command -v clang >/dev/null 2>&1; then
    clang -target aarch64-linux-gnu -nostdlib -static -Wl,-z,norelro -Wl,--build-id=none -o commander.elf commander.s
    telemetry_log "LINKER" "Clang static freestanding driver completed."
elif command -v as >/dev/null 2>&1 && command -v ld >/dev/null 2>&1; then
    as -march=armv8-a -o commander.o commander.s
    ld -s -N -o commander.elf commander.o
    rm -f commander.o
    telemetry_log "LINKER" "GNU binutils completed."
else
    echo -e "  ${C_AMBER}Error: No suitable assembler/linker found.${C_RESET}" >&2
    exit 1
fi
matrix_trace "Binary linked: commander.elf compliant with Android MMU pages."

# ==============================================================================
# PHASE 4: AUDIT & METRICS
# ==============================================================================
step_header "STAGE 04" "ARCHITECTURAL AUDIT & BINARY METRICS"

SIZE_BYTES=$(wc -c < commander.elf | tr -d ' ')
telemetry_log "FOOTPRINT" "Calculated ELF payload: ${C_GREEN}${SIZE_BYTES} bytes${C_RESET}"

if command -v readelf >/dev/null 2>&1; then
    ENTRY_POINT=$(readelf -h commander.elf | grep "Entry point address" | awk '{print $4}')
    telemetry_log "ENTRY_POINT" "Entry point: ${C_CYAN}${ENTRY_POINT}${C_RESET}"
fi

# ==============================================================================
# PHASE 5: RUNTIME EXECUTION
# ==============================================================================
step_header "STAGE 05" "OPERATIONAL EXECUTION & WIRE READOUT"

echo -e "  ${C_GRAY}Invoking kernel state transition...${C_RESET}\n"
sleep_tick

chmod +x commander.elf
./commander.elf
EXEC_CODE=$?

echo ""
if [[ "${EXEC_CODE}" -eq 0 ]]; then
    telemetry_log "STATUS" "Process dissolved cleanly: ${C_GREEN}exit code 0 (HOMEOSTATIC EQUILIBRIUM)${C_RESET}"
else
    telemetry_log "STATUS" "Process caught non-zero fault state: ${C_AMBER}exit code ${EXEC_CODE}${C_RESET}"
fi

echo -e "\n${C_GRAY}───────────────────────────────────────────────────────────────────────────────${C_RESET}"
echo -e "${C_GREEN}✔ PIPELINE COMPLETE: PURE HARDWARE COMMANDER RUNNING.${C_RESET}\n"
